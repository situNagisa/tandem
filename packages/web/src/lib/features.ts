export function sortFeatures(features: ProductFeature[]): ProductFeature[] {
  const order = new Map(FEATURE_GROUPS.map((group, index) => [group.id, index]))
  return [...features].sort((a, b) => (order.get(a.group) ?? 99) - (order.get(b.group) ?? 99))
}
